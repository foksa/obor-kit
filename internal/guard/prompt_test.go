// T-502: the UserPromptSubmit input Claude Code 2.1.312 gave a probe hook (testdata/prompt-*.json, paths redacted). It
// carries no origin field for any of them: a subagent's hand-back and another session's SendMessage come in their
// envelope; a raw post to the inbox socket (obor's) comes bare, so an untagged one cannot be told from typing.
func TestPromptCapturedPayloads(t *testing.T) {
	t.Parallel()
	f, o1 := promptFx(t, true)
	for _, c := range []struct {
		file   string
		guards bool
	}{
		{"prompt-typed.json", true},
		{"prompt-subagent-handback.json", false},
		{"prompt-inbox-obor.json", false},
		{"prompt-cross-session-message.json", false},
		{"prompt-inbox-untagged.json", true},
	} {
		b, err := os.ReadFile("testdata/" + c.file)
		var ev map[string]any
		if err != nil || json.Unmarshal(b, &ev) != nil || ev["hook_event_name"] != "UserPromptSubmit" {
			t.Fatalf("%s: %v", c.file, err)
		}
		ev["cwd"] = o1
		b, _ = json.Marshal(ev)
		var out bytes.Buffer
		UserPromptSubmit(b, f.Env(), &out)
		if got := strings.Contains(out.String(), guardLine); got != c.guards {
			t.Errorf("%s: guarded %v, want %v (output %q)", c.file, got, c.guards, out.String())
		}
		if !c.guards && out.Len() != 0 {
			t.Errorf("%s: output %q, want none", c.file, out.String())
		}
	}
}

