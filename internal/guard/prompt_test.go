// T-232, T-465: the handoff reminder text up to the session-specific numbers: the restart of the agent named.
func leadWhenOf(agent string) string {
	return "Hand off at the next logical break, not in the middle of work: when the current task or discussion has " +
		"reached its conclusion (nothing half-done, no question to the person open), write the Handoff section at the " +
		"top of BACKLOG.md (state, in-flight tasks, open decisions, next steps), commit it, then run `obor restart " +
		agent + " --fresh` (scheduled: it waits until you are idle). If the person is talking with you, ask them first."
}

var leadWhen = leadWhenOf("pj-lead")

// handoffFx: a project with lane L-01 (agent pj-l-01, task T-05) and a transcript at ctx tokens.
func handoffFx(t *testing.T, ctx int64) (f hfx, o1, tr string) {
	t.Helper()
	f, o1 = promptFx(t, true)
	tr = transcript(f, f.Base+"/projects/p/s1.jsonl", ctx)
	return f, o1, tr
}

// T-232: a lead above its limit gets the reminder on every prompt: a person's, obor's, a slash command, an
// auto-continuation, a machine envelope.
func TestPromptLeadHandoffReminderOnEveryPrompt(t *testing.T) {
	t.Parallel()
	f, _, tr := handoffFx(t, 600000)
	want := "obor (lead): context is 600k (> 500k). " + leadWhen
	for _, p := range []string{"what do you think about the plan?", "[obor heartbeat] tick", "[obor pj-int] merged T-05",
		"/obor:lead", "<task-notification>x</task-notification>", autoContinue} {
		if c := f.prompt(t, f.Root, p, session("s1", tr), "OBOR_ROLE=lead"); c != want {
			t.Errorf("prompt %q: context %q, want %q", p, c, want)
		}
	}
	if c := f.prompt(t, f.Root, "go on", session("s1", tr), "OBOR_ROLE=lead"); c != want {
		t.Errorf("the same session again: %q (a reminder every prompt, not once)", c)
	}
	if c := f.prompt(t, f.Root, "go on", `{"origin":{"kind":"auto-continuation"},"session_id":"s1","transcript_path":"`+tr+`"}`,
		"OBOR_ROLE=lead"); c != want {
		t.Errorf("auto-continuation origin: %q", c)
	}
	if c := f.prompt(t, f.Root, "go on", `{"transcript_path":"`+tr+`"}`, "OBOR_ROLE=lead"); c != want {
		t.Errorf("no session_id (the transcript's name): %q", c)
	}
}

// T-232: below the limit and limit 0 (off).
func TestPromptLeadHandoffLimits(t *testing.T) {
	t.Parallel()
	f, _, tr := handoffFx(t, 400000)
	ev := session("s1", tr)
	if c := f.prompt(t, f.Root, "hi", ev, "OBOR_ROLE=lead"); c != "" {
		t.Errorf("400k under the default 500k: %q", c)
	}
	f.Config(testkit.Set("handoff_tokens", 300000))
	if c := f.prompt(t, f.Root, "hi", ev, "OBOR_ROLE=lead"); c != "obor (lead): context is 400k (> 300k). "+leadWhen {
		t.Errorf("roles.lead.handoff_tokens 300000: %q", c)
	}
	f.Config(testkit.Set("handoff_tokens", 0))
	transcript(f, tr, 900000)
	if c := f.prompt(t, f.Root, "hi", ev, "OBOR_ROLE=lead"); c != "" {
		t.Errorf("handoff_tokens 0 → off, even at 900k: %q", c)
	}
}

// T-232, T-1108: only the lead gets the handoff reminder; a worker above any limit gets only the wrong-tab guard (a
// person's prompt) or nothing (obor's), and the integrator nothing.
func TestPromptHandoffOnlyForTheLead(t *testing.T) {
	t.Parallel()
	f, o1, tr := handoffFx(t, 900000)
	f.Config(testkit.Set("handoff_tokens", 1000))
	ev := session("w1", tr)
	if c := f.prompt(t, o1, "please fix the login bug", ev); !strings.Contains(c, guardLine) || strings.Contains(c, "context is") {
		t.Errorf("worker, person's prompt: %q, want the guard only", c)
	}
	if c := f.prompt(t, o1, "[obor pj-lead] go", ev); c != "" {
		t.Errorf("worker, obor's prompt: %q", c)
	}
	if c := f.prompt(t, f.Root, "hi", ev, "OBOR_ROLE=integrator"); c != "" {
		t.Errorf("integrator at 900k (handoff_tokens 1000): %q, want no reminder", c)
	}
	if c := f.prompt(t, f.Root, "hi", ev, "OBOR_ROLE=lead"); c == "" {
		t.Fatal("precondition: the lead at 900k gets the reminder")
	}
}

// hugeTail appends a size-byte user line to the transcript tr (its usage line then lies far behind the tail).
func hugeTail(t *testing.T, tr string, size int) {
	t.Helper()
	file, err := os.OpenFile(tr, os.O_APPEND|os.O_WRONLY, 0o600)
	if err != nil {
		t.Fatal(err)
	}
	defer file.Close()
	if _, err := file.WriteString(`{"type":"user","message":{"content":"` + strings.Repeat("x", size) + "\"}}\n"); err != nil {
		t.Fatal(err)
	}
}

// T-237 (RV-25 #1): a 64 MiB transcript tail → the read stops at its budget, no usage found → no reminder (fail open),
// well inside the hook timeout.
func TestPromptLeadHugeTranscriptFailsOpenFast(t *testing.T) {
	t.Parallel()
	f, _, tr := handoffFx(t, 600000)
	if c := f.prompt(t, f.Root, "hi", session("s1", tr), "OBOR_ROLE=lead"); c == "" {
		t.Fatal("precondition: a small transcript at 600k gets the reminder")
	}
	hugeTail(t, tr, 64<<20)
	start := time.Now()
	c := f.prompt(t, f.Root, "hi", session("s1", tr), "OBOR_ROLE=lead")
	if d := time.Since(start); d > 2*time.Second {
		t.Errorf("a 64 MiB tail took %s", d)
	}
	if c != "" {
		t.Errorf("a 64 MiB tail: %q, want no reminder (the usage line is beyond the read budget)", c)
	}
}
