// promptFx: lane L-01 (task/T-05, its worker pj-l-01: derived, T-1031) whose row names task T-05 (armed = false: no row).
func promptFx(t *testing.T, armed bool) (f hfx, o1 string) {
	t.Helper()
	f = newHfx(t)
	o1 = f.PlainLane("L-01", "task/T-05")
	f.Config()
	if armed {
		f.State("L-01", `{"lane":"L-01","task":"T-05"}`)
	}
	return f, o1
}

// prompt runs the wrong-tab guard on prompt typed in cwd; extra: more event fields (a JSON object text); env adds
// VAR=value. Returns the additionalContext ("" when no output) and checks the output's shape.
func (f hfx) prompt(t *testing.T, cwd, prompt, extra string, env ...string) string {
	t.Helper()
	ev := map[string]any{"hook_event_name": "UserPromptSubmit", "cwd": cwd, "prompt": prompt}
	if extra != "" {
		json.Unmarshal([]byte(extra), &ev)
		ev["cwd"], ev["prompt"] = cwd, prompt
	}
	b, _ := json.Marshal(ev)
	var out bytes.Buffer
	UserPromptSubmit(b, f.Env(env...), &out)
	if out.Len() == 0 {
		return ""
	}
	var v struct {
		HookSpecificOutput struct{ HookEventName, AdditionalContext string }
	}
	if err := json.Unmarshal(out.Bytes(), &v); err != nil || v.HookSpecificOutput.HookEventName != "UserPromptSubmit" {
		t.Fatalf("output %q: %v", out.String(), err)
	}
	return v.HookSpecificOutput.AdditionalContext
}

const guardLine = "I am worker pj-l-01 on T-05. Did you mean to type here?"

// guarded: each prompt gets the wrong-tab context; quiet: none does.
func (f hfx) guarded(t *testing.T, cwd, extra string, prompts ...string) {
	t.Helper()
	for _, p := range prompts {
		if c := f.prompt(t, cwd, p, extra); !strings.Contains(c, guardLine) {
			t.Errorf("prompt %q (%s): no guard, context %q", p, extra, c)
		}
	}
}

func (f hfx) quiet(t *testing.T, cwd, extra string, prompts ...string) {
	t.Helper()
	for _, p := range prompts {
		if c := f.prompt(t, cwd, p, extra); c != "" {
			t.Errorf("prompt %q (%s): guarded, want nothing", p, extra)
		}
	}
}

// promptRow is one guard row: prompts that arrive the same way (dir "sub": a subdirectory of the lane) and get the
// same verdict; needles: what a guarded context also says.
type promptRow struct {
	name    string
	guard   bool
	dir     string
	needles []string
	prompts []string
}

